import AppKit
import CoreImage
import CoreImage.CIFilterBuiltins
import Foundation

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let version = try String(contentsOf: root.appendingPathComponent("VERSION"), encoding: .utf8).trimmingCharacters(in: .whitespacesAndNewlines)
let parts = version.split(separator: ".", omittingEmptySubsequences: false)
guard parts.count == 3, parts.allSatisfy({ part in
    guard let n = UInt16(part) else { return false }
    return String(n) == part
}) else { fatalError("Expected canonical major.minor.patch VERSION") }
let link = "https://github.com/otcan/ble-clipboard/releases/tag/v\(version)"
let filter = CIFilter.qrCodeGenerator()
filter.message = Data(link.utf8); filter.correctionLevel = "M"
guard let image = filter.outputImage else { fatalError("QR generation failed") }
let context = CIContext(options: [.useSoftwareRenderer: true])
guard let cg = context.createCGImage(image, from: image.extent) else { fatalError("QR render failed") }
let original = NSBitmapImageRep(cgImage: cg)
var low = original.pixelsWide, high = -1
for y in 0..<original.pixelsHigh {
    for x in 0..<original.pixelsWide {
        if (original.colorAt(x: x, y: y)?.usingColorSpace(.deviceGray)?.whiteComponent ?? 1) < 0.5 {
            low = min(low, min(x, y)); high = max(high, max(x, y))
        }
    }
}
let modules = high - low + 1
let size = modules + 8
guard modules > 0, size <= 43,
      let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: size, pixelsHigh: size,
        bitsPerSample: 8, samplesPerPixel: 1, hasAlpha: false, isPlanar: false,
        colorSpaceName: .deviceWhite, bytesPerRow: size, bitsPerPixel: 8),
      let pixels = bitmap.bitmapData else { fatalError("QR exceeds Flipper viewport") }
let stride = (size + 7) / 8
var xbm = [UInt8](repeating: 0, count: stride * size)
for y in 0..<size {
    for x in 0..<size {
        let inside = (4..<(modules + 4)).contains(x) && (4..<(modules + 4)).contains(y)
        let black = inside && (original.colorAt(x: x - 4 + low, y: y - 4 + low)?.usingColorSpace(.deviceGray)?.whiteComponent ?? 1) < 0.5
        pixels[y * size + x] = black ? 0 : 255
        if black { xbm[y * stride + x / 8] |= 1 << (x % 8) }
    }
}
guard let png = bitmap.representation(using: .png, properties: [:]), let encoded = CIImage(data: png),
      let detector = CIDetector(ofType: CIDetectorTypeQRCode, context: context, options: [CIDetectorAccuracy: CIDetectorAccuracyHigh]),
      let decoded = detector.features(in: encoded.transformed(by: CGAffineTransform(scaleX: 8, y: 8))).first as? CIQRCodeFeature,
      decoded.messageString == link else { fatalError("Generated QR did not round-trip to the exact release URL") }

let header = """
// Generated by scripts/generate_companion_assets.swift from VERSION.
#pragma once
#define CLIPBOARD_APP_VERSION "\(version)"
#define CLIPBOARD_APP_VERSION_MAJOR \(parts[0])
#define CLIPBOARD_APP_VERSION_MINOR \(parts[1])
#define CLIPBOARD_APP_VERSION_PATCH \(parts[2])
#define CLIPBOARD_RELEASE_URL "\(link)"
#define CLIPBOARD_BUILD_API_MAJOR 88
#define CLIPBOARD_BUILD_API_MINOR 2
#define CLIPBOARD_BUILD_TARGET 7

"""
let rows = (0..<size).map { row in
    "    " + xbm[(row * stride)..<((row + 1) * stride)].map { String(format: "0x%02X", $0) }.joined(separator: ", ") + ","
}.joined(separator: "\n")
let qrHeader = """
// Generated QR bitmap: four-module quiet zone, Core Image correction level M.
#pragma once
#include <stdint.h>
#define CLIPBOARD_QR_SIZE \(size)
static const uint8_t clipboard_companion_qr[] = {
\(rows)
};

"""
let swift = """
// Generated by scripts/generate_companion_assets.swift from VERSION.
enum BuildRelease {
    static let version = "\(version)"
}

"""
let outputs: [(String, Data)] = [
    ("BluetoothClipboard/companion_version.h", Data(header.utf8)),
    ("BluetoothClipboard/companion_qr.h", Data(qrHeader.utf8)),
    ("BLEClipboardMac/Sources/BLEClipboardMac/BuildRelease.swift", Data(swift.utf8)),
    ("docs/assets/flipper-companions-qr.png", png),
]
let check = CommandLine.arguments.contains("--check")
for (path, data) in outputs {
    let url = root.appendingPathComponent(path)
    if check {
        guard (try? Data(contentsOf: url)) == data else { fatalError("Stale generated companion asset: \(path)") }
    } else {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try data.write(to: url, options: .atomic)
    }
}
print("\(check ? "Verified" : "Generated") \(version) companion metadata and \(size)x\(size) QR; exact URL decode passed.")
